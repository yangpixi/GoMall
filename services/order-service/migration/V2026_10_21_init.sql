CREATE TABLE IF NOT EXISTS gomall_order
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL CHECK ( status IN ('confirmed', 'released', 'payment_waiting')),

    total_amount BIGINT NOT NULL,
    discount_amount BIGINT NOT NULL,
    final_amount BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TRIGGER trigger_set_updated_at
    BEFORE UPDATE
    ON gomall_order
    FOR EACH ROW
EXECUTE PROCEDURE update_updated_at_column();

CREATE TABLE IF NOT EXISTS gomall_order_item
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL,

    unit_price BIGINT NOT NULL,
    total_price BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_order_item_order_id FOREIGN KEY (order_id) REFERENCES gomall_order (id) ON DELETE CASCADE
);

CREATE TRIGGER trigger_set_updated_at
    BEFORE UPDATE
    ON gomall_order_item
    FOR EACH ROW
EXECUTE PROCEDURE update_updated_at_column();

COMMENT ON COLUMN gomall_order_item.unit_price IS 'price per product';

CREATE TABLE IF NOT EXISTS gomall_order_address
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    address VARCHAR(1024) NOT NULL,
    recipient VARCHAR(20) NOT NULL,
    phone VARCHAR(20) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_order_address_order_id FOREIGN KEY (order_id) REFERENCES gomall_order (id) ON DELETE CASCADE
);

CREATE TRIGGER trigger_set_updated_at
    BEFORE UPDATE
    ON gomall_order_address
    FOR EACH ROW
EXECUTE PROCEDURE update_updated_at_column();




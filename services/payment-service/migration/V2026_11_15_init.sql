CREATE TABLE IF NOT EXISTS payment
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL,
    order_id       BIGINT       NOT NULL,

    amount         BIGINT       NOT NULL CHECK ( amount > 0 ),
    currency       VARCHAR(10)  NOT NULL DEFAULT 'CNY',

    channel        VARCHAR(10)  NOT NULL,
    status         VARCHAR(10)  NOT NULL DEFAULT 'pending' CHECK ( status IN ('pending', 'paid', 'cancelled') ),

    transaction_id VARCHAR(128) NOT NULL,

    expires_at     TIMESTAMPTZ  NOT NULL,
    paid_at        TIMESTAMPTZ,
    cancelled_at   TIMESTAMPTZ,

    created_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_payment_channel_transaction
    ON payment (channel, transaction_id)
    WHERE transaction_id IS NOT NULL;

CREATE INDEX idx_payment_order
    ON payment (order_id);

CREATE INDEX idx_payment_pending_expiration
    ON payment (expires_at)
    WHERE status = 'pending';

CREATE TRIGGER trigger_set_updated_at
    BEFORE UPDATE
    ON payment
    FOR EACH ROW
EXECUTE PROCEDURE update_updated_at_column();
